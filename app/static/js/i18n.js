const I18N = {
  lang: localStorage.getItem("rozzlf_lang") || "ar",
  t(key) {
    return (DICT[this.lang] && DICT[this.lang][key]) || DICT.en[key] || key;
  },
  setLang(lang) {
    this.lang = lang;
    localStorage.setItem("rozzlf_lang", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = this.t(el.dataset.i18n);
    });
    document.querySelectorAll("#lang-toggle .lang-flag, #dash-lang").forEach((el) => {
      el.textContent = lang === "ar" ? "EN" : "ع";
    });
    document.dispatchEvent(new CustomEvent("langchange"));
  },
  init() { this.setLang(this.lang); },
};
window.I18N = I18N;
window.t = (k) => I18N.t(k);
